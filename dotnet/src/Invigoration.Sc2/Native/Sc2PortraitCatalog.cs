            var (id, table, offset) = Entries[middle];
            if (id == unlockableId)
            {
                portrait = new Sc2Portrait(table, offset);
                return true;
            }

            if (id < unlockableId)
            {
                low = middle + 1;
            }
            else
            {
                high = middle - 1;
            }
        }

        portrait = default;
        return false;
