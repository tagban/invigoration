/// <summary>
/// A StarCraft II portrait: an image table and a cell offset in it. Superiority draws
/// these from 17 atlases (images/portrait-atlases/atlas-NN.png, NN = <see cref="Table"/>),
/// each a 6x6 grid of 152-pixel cells, with <see cref="Offset"/> counted row by row.
/// </summary>
public readonly record struct Sc2Portrait(ushort Table, ushort Offset)
{
    /// <summary>The portrait every account starts with (unlockable 2951153716).</summary>
    public static Sc2Portrait Default => new(0, 0);
}

